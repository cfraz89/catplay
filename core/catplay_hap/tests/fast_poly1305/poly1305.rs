use catplay_hap::fast_chacha::FastPoly1305;

fn main() {
    let key = [
        0x85, 0xd6, 0xbe, 0x78, 0x57, 0x55, 0x6d, 0x33, 0x7f, 0x44, 0x52, 0xfe, 0x42, 0xd5, 0x06, 0xa8, 0x01, 0x03, 0x80, 0x8a, 0xfb, 0x0d,
        0xb2, 0xfd, 0x4a, 0xbf, 0xf6, 0xaf, 0x41, 0x49, 0xf5, 0x1b,
    ];
    let msg = b"Cryptographic Forum Research Group";
    let expected = [
        0xa8, 0x06, 0x1d, 0xc1, 0x30, 0x51, 0x36, 0xc6, 0xc2, 0x2b, 0x8b, 0xaf, 0x0c, 0x01, 0x27, 0xa9,
    ];

    let mut poly = FastPoly1305::new(&key);
    poly.update(msg);
    assert_eq!(poly.finalize(), expected);
    assert_eq!(FastPoly1305::compute(&key, msg), expected);
}
